export type CopyKey = keyof typeof en;
const copy = { en, zh };

export function isLocale(value: string | null | undefined): value is Locale {
  return value === 'en' || value === 'zh';
}

export function builtInLocale(language: string | null | undefined, fallback: Locale): Locale {
  const base = language?.split('-')[0].toLowerCase();
  return isLocale(base) ? base : fallback;
}

export function text(locale: Locale, key: CopyKey, values?: Record<string, string | number>) {
  const template = copy[locale][key];
  return values ? template.replace(/\{([A-Za-z]+)\}/g, (match, name) => String(values[name] ?? match)) : template;
}

export function displayedDate(day: number, locale: Locale) {
  const format = new Intl.DateTimeFormat(locale === 'zh' ? 'zh-CN' : 'en-US', {
    month: 'short', day: 'numeric', timeZone: 'UTC',
  });
  return format.format(new Date(Date.UTC(REFERENCE_YEAR, 0, day)));
}

const LocaleContext = createContext<Locale>(DEFAULT_LOCALE);

export function LocaleProvider({ locale, children }: { locale: Locale; children: ReactNode }) {
  return <LocaleContext.Provider value={locale}>{children}</LocaleContext.Provider>;
}

export function useI18n() {
  const locale = useContext(LocaleContext);
  return {
    locale,
    t: (key: CopyKey, values?: Record<string, string | number>) => text(locale, key, values),
    date: (day: number) => displayedDate(day, locale),
    number: (value: number, digits = 1) => value.toLocaleString(locale === 'zh' ? 'zh-CN' : 'en-US', { maximumFractionDigits: digits }),
  };
}
